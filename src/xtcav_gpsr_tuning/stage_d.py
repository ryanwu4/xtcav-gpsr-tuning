"""Stage-D shared setup: 15673 conditioning, calibrated V_eff, target loading.

Conditioning convention (plan D2, critic-verified):
* every knob column sits at its box baseline u=0.5 (FF quads: recorded
  value_match BACTs == box baselines; movers/kickers: golden; energy offsets:
  box centered on baseline),
* EXCEPT L1PhaseSet = fixed anchor (−20°, critic M4 — recorded per-step KLYS
  deltas are BC11-feedback drift compensation and are dropped; the WITH-deltas
  refit is a pre-registered sensitivity variant) and L2PhaseSet = L2_ref +
  scanVal per step, both normalized through the xtcav23 box.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import torch

from . import paths
from .fit import FitSetup, calibrate_veff, load_setup

STAGE_D_CONFIG = (Path(__file__).resolve().parents[2] / "configs"
                  / "fit_stageD_15673.yaml")


def provenance(config_path=STAGE_D_CONFIG) -> dict:
    """Fingerprint of the code+config that produced an artifact (audit #8).
    The D0 gate compares this against each precal JSON, so a precal calibrated
    under different physics (e.g. before the handoff back-drift fix) can no
    longer silently bless a fit."""
    import hashlib
    src = Path(__file__).resolve().parent
    h = {}
    for f in ("fit.py", "screen.py", "stage_d.py", "segment.py",
              "identifiability.py", "targets_real.py"):
        h[f] = hashlib.sha256((src / f).read_bytes()).hexdigest()[:12]
    h["config"] = hashlib.sha256(Path(config_path).read_bytes()).hexdigest()[:12]
    return h


def check_provenance(artifact: dict, config_path=STAGE_D_CONFIG,
                     what: str = "artifact") -> None:
    """Raise unless the artifact was produced by the current code+config."""
    now, was = provenance(config_path), artifact.get("provenance")
    if was is None:
        raise SystemExit(
            f"GATE FAILURE: {what} carries no provenance stamp — it predates the "
            "audit fix. Re-run the precal stages under the current code.")
    diff = {k: (was.get(k), v) for k, v in now.items() if was.get(k) != v}
    if diff:
        raise SystemExit(
            f"GATE FAILURE: {what} was produced by different code/config; "
            f"changed since: {sorted(diff)}. Re-run the precal stages.")


def load_stage_d(config_path=STAGE_D_CONFIG, device: str = "cpu"):
    """load_setup + resolve voltage_V ('calibrate' -> calibrate_veff on the
    as-built 15673 segment)."""
    cfg, setup = load_setup(config_path, device=device)
    if cfg.get("voltage_V") == "calibrate":
        cfg["voltage_V"] = calibrate_veff(setup, float(cfg["cal_scaled"]))
    return cfg, setup


def _u(norm: dict, key: str, phys: float) -> float:
    j = norm["knob_keys"].index(key)
    lo, hi = float(norm["knob_low"][j]), float(norm["knob_high"][j])
    u = (phys - lo) / (hi - lo)
    assert 0.0 <= u <= 1.0, f"{key}={phys} outside box [{lo},{hi}] (u={u:.3f})"
    return u


def conditioning(setup: FitSetup, cfg: dict,
                 l1_deltas_deg: np.ndarray | None = None) -> torch.Tensor:
    """(n_steps, n_knob) normalized knob rows for the real scan geometry: the
    model's baseline row (u=0.5 everywhere for xtcav23; the bundle baselines for
    a CNF — golden injector, so drive_fraction sits at 0.75, u=0.643), with the
    L1 anchor and the per-step L2 overwritten."""
    mc = json.loads(Path(cfg["machine_config"]).read_text())
    scan = np.asarray(mc["L2_scan_vals_deg"], float)
    norm = setup.norm
    base = setup.baseline_norm.detach().cpu().double().unsqueeze(0).repeat(len(scan), 1)
    l1 = float(cfg["l1_anchor_deg"])
    for i, sv in enumerate(scan):
        l1_i = l1 + (float(l1_deltas_deg[i]) if l1_deltas_deg is not None else 0.0)
        base[i, norm["knob_keys"].index("L1PhaseSet")] = _u(norm, "L1PhaseSet", l1_i)
        base[i, norm["knob_keys"].index("L2PhaseSet")] = _u(
            norm, "L2PhaseSet", float(cfg["l2_ref_deg"]) + sv)
    return base.to(setup.device)


def load_targets(cfg: dict, device: str = "cpu") -> dict:
    """targets.npz -> tensors in the ForwardModel's (sign, step, ...) layout.

    npz layout is (step, sign[plus,neg], ny, nx); the model emits (2, B, ny, nx)
    with sign order (+1, −1). CANONICAL pairing maps plus->+1; the other three
    orientation/pairing hypotheses are generated by flip_rows / swap_signs.
    """
    d = np.load(paths.REPO_ROOT / cfg["targets_npz"])
    imgs = torch.tensor(d["images"], dtype=torch.float64,
                        device=device).permute(1, 0, 2, 3)
    splits = torch.tensor(d["splits"], dtype=torch.float64, device=device).T
    floors = torch.tensor(d["floors_tv"], dtype=torch.float64, device=device).T
    off = torch.tensor(d["off_images"], dtype=torch.float64, device=device)
    mask = torch.tensor(d["mask"], dtype=torch.float64, device=device)
    # step weights: cap at 1, downweight targets noisier than the median floor
    fmed = float(torch.nanmedian(floors))
    w = (fmed / floors.clamp_min(fmed)).nan_to_num(0.0)
    # off channel gets the SAME treatment (audit #2: it used to enter the loss
    # as an unweighted mean while the streaked channel was noise-weighted)
    if "off_floors_tv" in d:
        off_floors = torch.tensor(d["off_floors_tv"], dtype=torch.float64,
                                  device=device)
        ofmed = float(torch.nanmedian(off_floors))
        w_off_step = (ofmed / off_floors.clamp_min(ofmed)).nan_to_num(0.0)
    else:                      # pre-gate targets.npz
        off_floors = torch.full_like(w[0], float("nan"))
        w_off_step = torch.ones_like(w[0])
    return {"images": imgs, "splits": splits, "floors": floors, "off": off,
            "off_floors": off_floors, "off_step_weights": w_off_step,
            "mask": mask, "step_weights": w,
            "n_shots": torch.tensor(d["n_shots"]).T,
            "scan_vals_deg": d["scan_vals_deg"], "steps": d["steps"],
            "provenance": json.loads(str(d["provenance"]))}


def orient(imgs: torch.Tensor, flip_rows: bool, swap_signs: bool) -> torch.Tensor:
    """Apply one of the 4 discrete orientation/pairing hypotheses to a
    (2, B, ny, nx) target stack (COM-centering commutes with the row flip)."""
    out = imgs
    if flip_rows:
        out = out.flip(-2)
    if swap_signs:
        out = out.flip(0)
    return out
